#!/usr/bin/env python3
"""Independent mathematical and physical-word oracles for wide fields."""
import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'tests/semantic/regression/gcc-wide-bitfield-words-v60b.c'
MASK = (1 << 36) - 1
SIGN = 1 << 35


def word(x):
    return '0%012oUL' % (x & MASK)


def pair(x, mode):
    if mode == 71:
        hi = (x >> 35) & MASK
        lo = (x & (SIGN - 1)) | (hi & SIGN)
    else:
        hi = (x >> 36) & MASK
        lo = x & MASK
    return word(hi) + ', ' + word(lo)


def raw(x):
    return pair(x, 72)


def render():
    lines = ["""/* Generated by tools/gen-wide-bitfield-oracle-v60b.py.
 * Each expected physical word comes from independent Python integers.
 * The wide value travels through volatile raw limbs, not C wide
 * constant folding. The record starts from independent physical words.
 * Test signed/unsigned extraction and insertion separately.
 */
typedef union {
    signed long long s;
    unsigned long long u;
    unsigned long w[2];
} arithmetic;
static volatile arithmetic input, output;
volatile unsigned int fail_id;

struct vector {
    unsigned long r0, r1, i0, i1, h, l;
};

#ifdef __LONG_LONG_72BIT__
#define PAIR(h71,l71,h72,l72) h72,l72
#else
#define PAIR(h71,l71,h72,l72) h71,l71
#endif

#define TEST_SHAPE(NAME,TYPE,MEMBER,FIELDS) \\
typedef union { struct { FIELDS } f; unsigned long w[2]; } NAME; \\
static TYPE NAME##_get(NAME *p) __attribute__((noinline)); \\
static TYPE NAME##_get(NAME *p) { return p->f.field; } \\
static void NAME##_set(NAME *p, TYPE v) __attribute__((noinline)); \\
static void NAME##_set(NAME *p, TYPE v) { p->f.field=v; } \\
static int NAME##_run(unsigned id, const struct vector *v, unsigned n) \\
{ \\
    NAME obj; \\
    unsigned i; \\
    if (sizeof(obj)!=8) { fail_id=id; return 1; } \\
    for(i=0;i<n;++i) { \\
        fail_id=id+i*2+1; \\
        obj.w[0]=v[i].r0; obj.w[1]=v[i].r1; \\
        output.MEMBER=NAME##_get(&obj); \\
        if(output.w[0]!=v[i].h || output.w[1]!=v[i].l) return 1; \\
        ++fail_id; \\
        obj.w[0]=v[i].i0; obj.w[1]=v[i].i1; \\
        input.w[0]=v[i].h; input.w[1]=v[i].l; \\
        NAME##_set(&obj,input.MEMBER); \\
        if(obj.w[0]!=v[i].r0 || obj.w[1]!=v[i].r1) return 1; \\
    } \\
    return 0; \\
}
"""]
    shapes = []
    for width in (37, 52, 53, 70, 71):
        pad = 72 - width
        for sign in (True, False):
            for first in (True, False):
                name = ('s' if sign else 'u') + str(width) + ('a' if first else 'b')
                typ = 'signed long long' if sign else 'unsigned long long'
                fld = '%s field:%d;' % (typ, width)
                pd = 'unsigned long long pad:%d;' % pad
                fields = fld + ' ' + pd if first else pd + ' ' + fld
                lines.append('TEST_SHAPE(%s, %s, %s, %s)\n' %
                             (name, typ, 's' if sign else 'u', fields))
                lines.append('static const struct vector %s_vectors[] = {' % name)
                mask = (1 << width) - 1
                shift = pad if first else 0
                bits = (1 << 72) - 1
                guard = (0x987654321abcdef123 & bits) & ~(mask << shift)
                payloads = {0, 1, (1 << 35) - 1, 1 << 35,
                            1 << (width - 1), (1 << (width - 1)) - 1,
                            mask, (0x123456789abcdef & mask)}
                for payload in sorted(payloads):
                    value = payload
                    if sign and payload & (1 << (width - 1)):
                        value -= 1 << width
                    r = guard | (payload << shift)
                    init = guard | ((payload ^ mask) << shift)
                    lines.append('    { %s, %s, PAIR(%s, %s) },' %
                                 (raw(r), raw(init), pair(value, 71), pair(value, 72)))
                lines.append('};\n')
                shapes.append(name)
    lines += ['int main(void)', '{']
    for i, name in enumerate(shapes, 1):
        lines.append('    if (%s_run(%d, %s_vectors, sizeof(%s_vectors)/sizeof(struct vector))) return 1;' %
                     (name, i*32, name, name))
    lines += ['    fail_id=0;', '    return 0;', '}', '']
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    source = render()
    if args.check:
        assert OUT.read_text() == source, 'generated source mismatch'
        print('PASS: wide-bitfield oracle source')
    else:
        OUT.write_text(source, encoding='ascii')


if __name__ == '__main__':
    main()
