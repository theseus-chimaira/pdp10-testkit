#!/usr/bin/env python3
"""Independent Decimal-based oracle for canonical finite D-format words."""
from decimal import Decimal, localcontext, ROUND_HALF_EVEN
from pathlib import Path
import random
import sys

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'tests/semantic/regression/pdp10-buffer-float-oracle-v59v.c'
B = 1 << 35
MASK = (1 << 36) - 1
M = 1 << 61

def value(m, e, negative=False):
    """m is the exact unsigned 62-bit fraction; e is unbiased exponent."""
    raw = ((e + 128) << 62) | m if m else 0
    if negative:
        raw = -raw
    raw %= 1 << 71
    hi, lo = divmod(raw, B)
    lo |= hi & B
    x = Decimal(m) * (Decimal(2) ** (e - 62))
    if negative:
        x = -x
    return hi, lo, x

def fmt_decimal(x, conv, p, flags='', width=0):
    # Decimal's independent correctly rounded decimal formatter is used
    # for fixed/scientific. General notation is selected after rounding.
    neg = x.is_signed()
    x = abs(x)
    lower = conv.lower()
    if lower == 'g':
        p = max(p, 1)
        if x:
            x = x.quantize(Decimal(1).scaleb(x.adjusted() - p + 1))
        exp = x.adjusted() if x else 0
        scientific = exp < -4 or exp >= p
        places = p - 1 if scientific else max(0, p - 1 - exp)
    else:
        scientific = lower == 'e'
        places = p
    if scientific:
        if not x:
            mantissa, exp = format(x, '.%df' % places), 0
        else:
            mantissa, ex = format(x, '.%de' % places).split('e')
            exp = int(ex)
    else:
        mantissa = format(x, '.%df' % places)
        exp = 0
    if lower == 'g' and '#' not in flags and '.' in mantissa:
        mantissa = mantissa.rstrip('0').rstrip('.')
    if '#' in flags and '.' not in mantissa:
        mantissa += '.'
    if scientific:
        mantissa += ('E' if conv.isupper() else 'e') + '%+03d' % exp
    sign = '-' if neg else '+' if '+' in flags else ' ' if ' ' in flags else ''
    pad = max(0, width - len(sign) - len(mantissa))
    if '-' in flags:
        return sign + mantissa + ' ' * pad
    if '0' in flags:
        return sign + '0' * pad + mantissa
    return ' ' * pad + sign + mantissa

def generate():
    lines = [
        '/* Generated by tools/gen-p10stdio-float-oracle-v59v.py.',
        ' * Exact raw D-format inputs; independent host Decimal expectations. */',
        '#include <stdio.h>', '#include <string.h>', '#include <limits.h>',
        'volatile unsigned fail_id;',
        'static char output[256];',
        'static int check(unsigned long hi, unsigned long lo,',
        '                 const char *fmt, const char *expected, unsigned id)',
        '{',
        '    union { double d; unsigned long w[2]; } bits;',
        '    int n;',
        '    bits.w[0] = hi; bits.w[1] = lo;',
        '    fail_id = id;',
        '    n = sprintf(output, fmt, bits.d);',
        '    return n == (int)strlen(expected) && !strcmp(output, expected);',
        '}',
        'int main(void)', '{'
    ]
    cases = [
        (0,0,False,'f',6,'',0),
        (M,0,False,'f',0,'',0), # 0.5 tie
        (M+1,0,False,'f',0,'',0),
        (2*M-1,-1,False,'f',0,'',0),
        (3*M//2,1,False,'f',0,'',0), # 1.5
        (5*M//4,2,False,'f',0,'',0), # 2.5
        (7*M//4,2,False,'f',0,'',0), # 3.5
        (M,-1,True,'f',0,'',0),
        (M,1,False,'f',6,'',0),
        (M,1,True,'f',6,'0',12),
        (M,1,False,'f',0,'+#',8),
        (M,1,False,'f',2,'- ',9),
        (3*M//2,0,False,'f',1,'',0),
        (M,0,False,'f',3,'',0),
        (2*M-1,4,False,'g',1,'',0),
        (2*M-1,4,False,'G',1,'#',0),
        (M,1,False,'g',6,'#',0),
        (0,0,False,'g',0,'#',0),
        (M,-12,False,'g',6,'',0),
        (M,-13,False,'g',6,'',0),
        (M,-14,False,'g',6,'',0),
        (M,127,False,'f',0,'',0),
        (2*M-1,127,True,'G',18,'',0),
        (M,-128,False,'f',190,'',0),
        (2*M-1,-128,True,'e',21,'',0),
        (M,-128,False,'g',6,'',0),
        (M,1,False,'e',0,'#',0),
        (0,0,False,'E',4,'',0),
        (M+1,1,False,'f',62,'',0),
        (M+1,1,True,'g',22,'',0),
    ]
    rng = random.Random(59022)
    for i in range(12):
        cases.append((rng.randrange(M, 2*M), rng.randrange(-128,128),
                      bool(i&1), 'fge'[i%3], (0,6,17,25)[i%4], '', 0))
    with localcontext() as ctx:
        ctx.prec = 400
        ctx.rounding = ROUND_HALF_EVEN
        for i, (m,e,neg,c,p,flags,width) in enumerate(cases,1):
            hi,lo,x = value(m,e,neg)
            fmt = '%' + flags + (str(width) if width else '') + '.%d%s' % (p,c)
            expected = fmt_decimal(x,c,p,flags,width)
            lines += ['    if (!check(0%oUL, 0%oUL, "%s",' % (hi,lo,fmt),
                      '               "%s", %d)) return 1;' % (expected,i)]
    lines += [
        '    fail_id = 100;',
        '    if (snprintf(output, 5, "%.6f", 1.5) != 8 ||',
        '        strcmp(output, "1.50")) return 2;',
        '    fail_id = 101;',
        '    if (snprintf((char *)0, 0, "%.1000000f", 1.0) != 1000002)',
        '        return 3;',
        '    fail_id = 102;',
        '    if (snprintf(output, sizeof(output), "%.*f", INT_MAX, 1.0) != -1)',
        '        return 4;',
        '    fail_id = 103;',
        '    if (sprintf(output, "%d|%.0f|%g|%s", 9, 2.5, 0.5, "ok") != 10 ||',
        '        strcmp(output, "9|2|0.5|ok")) return 5;',
        '    fail_id = 0;',
        '    return 0;', '}', ''
    ]
    return '\n'.join(lines)

if __name__ == '__main__':
    text = generate()
    if '--check' in sys.argv:
        assert OUT.read_text() == text
    else:
        OUT.write_text(text)
    print('PASS: independent Decimal oracle source (42 raw cases plus 4 buffer/ABI guards)')
