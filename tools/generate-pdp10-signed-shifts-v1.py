#!/usr/bin/env python3
"""Independent target 9/18/36-bit signed arithmetic shift assertions.

The upstream 20020108-1.c has only 8/16/32-bit mode guards, so none
execute for CHAR_BIT=9. Explicitly select arithmetic right-shift of
negative values as a PDP-10 target policy; it is not portable C89.
"""

import argparse
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT/'tests/semantic/regression/pdp10-signed-right-shifts-v1.c'


def source():
    text=[
        '/* Signed 9/18/36-bit right shift reference, version 1.',
        ' * Arithmetic right shifts of negative signed integers are',
        ' * a PDP-10 target policy; C89 leaves their result implementation',
        ' * defined. All expectations are generated by Python integers.',
        ' * This exercises the signed shift family omitted by the',
        ' * upstream 20020108-1.c on nine-bit-char targets.',
        ' */',
        '#include <limits.h>',
        '#if CHAR_BIT != 9',
        '#error PDP10 nine-bit-char target expected',
        '#endif',
        'extern void abort(void);',
        'volatile unsigned int fail_id;',
        'static volatile unsigned int shift_v1;',
        'static volatile signed char neg9_v1;',
        'static volatile signed short neg18_v1;',
        'static volatile signed int neg36_v1;',
        '']
    for width in (9,18,36):
        answers=[(-(1<<(width-1)))>>n for n in range(width)]
        text.append('static const signed long expected_min_%d_v1[%d] = {'%(width,width))
        for start in range(0,width,4):
            values=[]
            for number in answers[start:start+4]:
                # Avoid parsing 2**35 as an unsigned C literal on the
                # 36-bit target; the first minimum needs two signed
                # in-range operands, not signed overflow.
                if width==36 and number==-(1<<35):
                    values.append('(-34359738367L - 1L)')
                else:
                    values.append('%dL'%number)
            text.append('    '+', '.join(values)+(',' if start+4<width else ''))
        text.extend(['};',''])
    text.extend(['int','main(void)','{','    unsigned int i;',''])
    for width in (9,18,36):
        var='neg%d_v1'%width
        mini=-(1<<(width-1))
        value='(-34359738367L - 1L)' if width==36 else str(mini)
        text+=['    %s = -1;'%var,
               '    for (i=0U; i<%dU; i++) {'%width,
               '        shift_v1 = i;',
               '        if ((signed int)(%s >> shift_v1) != -1) {'%var,
               '            fail_id = %dU + i;'%(width*100),
               '            abort();',
               '        }',
               '    }',
               '    %s = %s;'%(var,value),
               '    for (i=0U; i<%dU; i++) {'%width,
               '        shift_v1 = i;',
               '        if ((signed long)(%s >> shift_v1) !='%var,
               '            expected_min_%d_v1[i]) {'%width,
               '            fail_id = %dU + i;'%(width*100+50),
               '            abort();',
               '        }',
               '    }','']
    text.extend(['    return 0;','}',''])
    return '\n'.join(text)


def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--write',action='store_true')
    args=p.parse_args()
    expected=source()
    if args.write:
        OUTPUT.write_text(expected,encoding='ascii')
        print('GENERATED',OUTPUT,len(expected),'ASCII bytes')
        return 0
    if not OUTPUT.is_file() or OUTPUT.read_text(encoding='ascii')!=expected:
        print('ERROR: PDP10 signed shift oracle stale or modified',file=sys.stderr)
        return 1
    print('PDP10 signed 9/18/36-bit right-shift arithmetic: PASS (63 counts, 126 assertions)')
    return 0


if __name__=='__main__':
    sys.exit(main())
