"$DAS_ROOT/das" -A -F -O "$TMP.skipfold.dxr" "$TEST_ROOT/dxr-optimize-skip-fold.s"
"$TEST_ROOT/dxr-optimize-skip-fold-check.py" "$TMP.skipfold.dxr"
"$DAS_ROOT/das" -A -F -O "$TMP.unaryfold.dxr" "$TEST_ROOT/dxr-optimize-unary-fold.s"
"$TEST_ROOT/dxr-optimize-unary-fold-check.py" "$TMP.unaryfold.dxr"
"$DAS_ROOT/das" -A -F -O "$TMP.movnov.dxr" "$TEST_ROOT/dxr-optimize-movn-overflow-v1.s"
"$TEST_ROOT/dxr-optimize-movn-overflow-v1-check.py" "$TMP.movnov.dxr"
"$DAS_ROOT/das" -A -F -O "$TMP.overwrite.dxr" "$TEST_ROOT/dxr-optimize-overwrite.s"
"$TEST_ROOT/dxr-optimize-overwrite-check.py" "$TMP.overwrite.dxr"
"$DAS_ROOT/das" -A -F -O "$TMP.faultorder.dxr" "$TEST_ROOT/dxr-optimize-fault-order-v1.s"
"$TEST_ROOT/dxr-optimize-fault-order-v1-check.py" "$TMP.faultorder.dxr"
