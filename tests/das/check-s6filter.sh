"$TEST_ROOT/dxr-optimize-skip-state-v2-check.py" "$TMP.skipstate.dxr"
"$DAS_ROOT/das" -A -F -L "$TMP.labelxct.labels" -O "$TMP.labelxct.dxr" "$TEST_ROOT/dxr-optimize-label-xct-v1.s"
"$TEST_ROOT/dxr-optimize-label-xct-v1-check.py" "$TMP.labelxct.dxr" "$TMP.labelxct.labels"
