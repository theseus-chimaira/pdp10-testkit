"$TEST_ROOT/dxr-optimize-addi-window-check.py" "$TMP.addiwin.dxr"
"$DAS_ROOT/das" -A -F -O "$TMP.addiov.dxr" "$TEST_ROOT/dxr-optimize-addi-overflow-v1.s"
"$TEST_ROOT/dxr-optimize-addi-overflow-v1-check.py" "$TMP.addiov.dxr"
"$DAS_ROOT/das" -A -F -O "$TMP.movefwd.dxr" "$TEST_ROOT/dxr-optimize-move-forward-v1.s"
"$TEST_ROOT/dxr-optimize-move-forward-v1-check.py" "$TMP.movefwd.dxr"
"$DAS_ROOT/das" -A -F -O "$TMP.moveifwd.dxr" "$TEST_ROOT/dxr-optimize-movei-forward-v1.s"
"$TEST_ROOT/dxr-optimize-movei-forward-v1-check.py" "$TMP.moveifwd.dxr"
"$DAS_ROOT/das" -A -F -O "$TMP.setmfwd.dxr" "$TEST_ROOT/dxr-optimize-setm-forward-v1.s"
"$TEST_ROOT/dxr-optimize-setm-forward-v1-check.py" "$TMP.setmfwd.dxr"
"$DAS_ROOT/das" -A -F -O "$TMP.zerocopy.dxr" "$TEST_ROOT/dxr-optimize-zero-copy-v1.s"
"$TEST_ROOT/dxr-optimize-zero-copy-v1-check.py" "$TMP.zerocopy.dxr"
"$DAS_ROOT/das" -A -F -O "$TMP.jrstnext.dxr" "$TEST_ROOT/dxr-optimize-jrst-next-v2.s"
"$DAS_ROOT/das" -A -O "$TMP.jrstnext.expected.dxr" "$TEST_ROOT/dxr-optimize-jrst-next-v2-expected.s"
cmp "$TMP.jrstnext.dxr" "$TMP.jrstnext.expected.dxr"
"$DAS_ROOT/das" -A -F -O "$TMP.lit.dxr" "$TEST_ROOT/dxr-optimize-literal.s"
"$TEST_ROOT/dxr-optimize-literal-check.py" "$TMP.lit.dxr"
"$DAS_ROOT/das" -A -F -O "$TMP.movei.dxr" "$TEST_ROOT/dxr-optimize-movei.s"
"$TEST_ROOT/dxr-optimize-movei-check.py" "$TMP.movei.dxr"
