#!/bin/sh
set -eu
TEST_ROOT=${TEST_ROOT:-$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)}
DAS_ROOT=${DAS_ROOT:?set DAS_ROOT to the DAS source tree}
TMPDIR=${TMPDIR:?set TMPDIR to a writable temporary directory}
TMP=$TMPDIR/das-s6filter.$$
trap 'rm -f "$TMP".*' 0 1 2 3 15
printf 'main:\r\n\tmove 1,2 ; lower comment\r\n\thalt\r\n' > "$TMP.in"
"$DAS_ROOT/s6filter" - "$TMP.s6" < "$TMP.in"
printf 'MAIN:\n MOVE 1,2 ; LOWER COMMENT\n HALT\n' > "$TMP.canon"
"$DAS_ROOT/das" -S -O "$TMP.s6.dxr" "$TMP.s6"
"$DAS_ROOT/das" -A -O "$TMP.ascii.dxr" "$TMP.canon"
cmp "$TMP.s6.dxr" "$TMP.ascii.dxr"
printf '.SIXBIT /abc/\n' > "$TMP.bad"
if "$DAS_ROOT/s6filter" "$TMP.bad" "$TMP.bad.s6" >/dev/null 2>&1; then
    echo 's6filter accepted lowercase semantic data' >&2; exit 1
fi
printf 'MOVE 1,{FOO}\n' > "$TMP.bad"
if "$DAS_ROOT/s6filter" "$TMP.bad" "$TMP.bad.s6" >/dev/null 2>&1; then
    echo 's6filter accepted non-SIXBIT punctuation' >&2; exit 1
fi
"$DAS_ROOT/das" -A -F -O "$TMP.opt.dxr" "$TEST_ROOT/dxr-optimize.s"
"$TEST_ROOT/dxr-optimize-check.py" "$TMP.opt.dxr"
"$DAS_ROOT/das" -A -F -O "$TMP.win.dxr" "$TEST_ROOT/dxr-optimize-window.s"
"$TEST_ROOT/dxr-optimize-window-check.py" "$TMP.win.dxr"
