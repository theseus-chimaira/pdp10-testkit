/* Independent high36:low35 integer and SF/DF bit-pattern oracle.
   The table was generated by exact host integer arithmetic. */
typedef unsigned long W;
typedef union { unsigned long long value; W w[2]; } Wide;
typedef union { float value; W w; } Single;
typedef union { double value; W w[2]; } Double;
static volatile Wide in, out;
static volatile Single sf;
static volatile Double df;
volatile unsigned fail_id;
static const struct sample {
    W ih, il, sf, dh, dl, sh, sl, rh, rl;
    int sf_inverse, df_inverse;
} cases[] = {
    {00UL, 00UL, 00UL, 00UL, 00UL, 00UL, 00UL, 00UL, 00UL, 1, 1},
    {00UL, 01UL, 0201400000000UL, 0201400000000UL, 00UL, 00UL, 01UL, 00UL, 01UL, 1, 1},
    {00UL, 0377777777777UL, 0244400000000UL, 0243777777777UL, 0377000000000UL, 01UL, 00UL, 00UL, 0377777777777UL, 1, 1},
    {01UL, 00UL, 0244400000000UL, 0244400000000UL, 00UL, 01UL, 00UL, 01UL, 00UL, 1, 1},
    {01UL, 021UL, 0244400000000UL, 0244400000000UL, 010400000000UL, 01UL, 00UL, 01UL, 021UL, 1, 1},
    {0200000000200UL, 00UL, 0306400000000UL, 0306400000000UL, 0200000000000UL, 0200000000000UL, 00UL, 0200000000200UL, 00UL, 1, 1},
    {0200000000200UL, 01UL, 0306400000001UL, 0306400000000UL, 0200000000000UL, 0200000000400UL, 00UL, 0200000000200UL, 00UL, 1, 1},
    {0377777777777UL, 0377777777777UL, 0307400000000UL, 0307400000000UL, 00UL, 0400000000000UL, 0400000000000UL, 0400000000000UL, 0400000000000UL, 1, 1},
    {0400000000000UL, 0400000000000UL, 0307400000000UL, 0307400000000UL, 00UL, 0400000000000UL, 0400000000000UL, 0400000000000UL, 0400000000000UL, 1, 1},
    {0400000000000UL, 0400000000021UL, 0307400000000UL, 0307400000000UL, 00UL, 0400000000000UL, 0400000000000UL, 0400000000000UL, 0400000000000UL, 1, 1},
    {0400000000400UL, 0400000000000UL, 0307400000000UL, 0307400000000UL, 0200000000000UL, 0400000000000UL, 0400000000000UL, 0400000000400UL, 0400000000000UL, 1, 1},
    {0400000000400UL, 0400000000001UL, 0307400000001UL, 0307400000000UL, 0200000000000UL, 0400000001000UL, 0400000000000UL, 0400000000400UL, 0400000000000UL, 1, 1},
    {0777777777777UL, 0777777777777UL, 0310400000000UL, 0310400000000UL, 00UL, 00UL, 00UL, 00UL, 00UL, 0, 0}
};

int main(void)
{
    unsigned i;
    for (i = 0; i < sizeof(cases)/sizeof(cases[0]); ++i) {
        const struct sample *p = &cases[i];
        in.w[0] = p->ih;
        in.w[1] = p->il;
        fail_id = i * 4 + 1;
        sf.value = (float)in.value;
        if (sf.w != p->sf) return 1;
        ++fail_id;
        df.value = (double)in.value;
        if (df.w[0] != p->dh || df.w[1] != p->dl) return 2;
        ++fail_id;
        if (p->sf_inverse) {
            sf.w = p->sf;
            out.value = (unsigned long long)sf.value;
            if (out.w[0] != p->sh ||
                (out.w[1] & 0377777777777UL) != (p->sl & 0377777777777UL)) return 3;
        }
        ++fail_id;
        if (p->df_inverse) {
            df.w[0] = p->dh;
            df.w[1] = p->dl;
            out.value = (unsigned long long)df.value;
            if (out.w[0] != p->rh ||
                (out.w[1] & 0377777777777UL) != (p->rl & 0377777777777UL)) return 4;
        }
    }
    fail_id = 101;
    sf.value = -0.5F;
    out.value = (unsigned long long)sf.value;
    if (out.w[0] || out.w[1]) return 5;
    fail_id = 102;
    df.value = 1.99;
    out.value = (unsigned long long)df.value;
    if (out.w[0] || out.w[1] != 1) return 6;
    fail_id = 0;
    return 0;
}
